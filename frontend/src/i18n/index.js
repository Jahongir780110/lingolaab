export function useLocale() {
  const route = useRoute()
  const locale = computed(() => route.params.locale || 'en')
  function t(key) { return messages[locale.value]?.[key] ?? messages.en[key] ?? key }
  function localizedPath(path) { return locale.value === 'en' ? path : `/${locale.value}${path === '/' ? '/' : path}` }
  return { locale, t, localizedPath }
}
